-- Journal des mouvements de stock.
--
-- Raison d'être : jusqu'ici le stock d'un produit était un simple nombre que
-- plusieurs chemins écrivaient, dont le formulaire de modification du produit,
-- qui le réécrivait en valeur absolue et effaçait donc silencieusement les
-- ventes enregistrées entre-temps. Désormais toute variation laisse une ligne
-- ici, avec son auteur et son motif.
--
-- « variation » est signée : négative pour une sortie, positive pour une
-- entrée. La somme des variations d'un produit doit donc être égale à son
-- quantite_stock. C'est un invariant vérifiable, et le seul moyen de détecter
-- qu'un chemin a contourné le journal.

CREATE TABLE public.mouvement_stock (
    id bigint NOT NULL,
    produit_id bigint NOT NULL,
    type character varying(20) NOT NULL,
    variation integer NOT NULL,
    stock_avant integer NOT NULL,
    stock_apres integer NOT NULL,
    motif character varying(20),
    commentaire character varying(300),
    -- Numéro de la vente ou de la livraison à l'origine du mouvement, pour
    -- remonter du journal à l'opération sans jointure sur deux tables.
    reference character varying(30),
    auteur_id bigint,
    cree_le timestamp(6) with time zone,

    CONSTRAINT mouvement_stock_type_check CHECK (((type)::text = ANY ((ARRAY['INITIAL'::character varying, 'ENTREE'::character varying, 'SORTIE'::character varying, 'RETOUR'::character varying, 'AJUSTEMENT'::character varying])::text[]))),
    CONSTRAINT mouvement_stock_motif_check CHECK ((motif IS NULL) OR ((motif)::text = ANY ((ARRAY['CASSE'::character varying, 'PEREMPTION'::character varying, 'VOL'::character varying, 'ERREUR_SAISIE'::character varying, 'DON'::character varying, 'AUTRE'::character varying])::text[]))),

    -- Un mouvement est toujours attribuable, sauf la reprise d'historique
    -- insérée plus bas, qui précède la mise en place du journal et n'a donc
    -- pas d'auteur réel. Interdit à l'application d'écrire un mouvement
    -- anonyme.
    CONSTRAINT mouvement_stock_auteur_check CHECK ((auteur_id IS NOT NULL) OR ((type)::text = 'INITIAL'::text))
);

ALTER TABLE public.mouvement_stock ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.mouvement_stock_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.mouvement_stock
    ADD CONSTRAINT mouvement_stock_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.mouvement_stock
    ADD CONSTRAINT mouvement_stock_produit_id_fkey FOREIGN KEY (produit_id) REFERENCES public.produit(id);

ALTER TABLE ONLY public.mouvement_stock
    ADD CONSTRAINT mouvement_stock_auteur_id_fkey FOREIGN KEY (auteur_id) REFERENCES public.utilisateur(id);

-- L'historique se consulte produit par produit, du plus récent au plus ancien.
CREATE INDEX idx_mouvement_stock_produit_date
    ON public.mouvement_stock (produit_id, cree_le DESC);

-- --- Reprise de l'existant -------------------------------------------------
-- Sans cette ligne par produit, la somme des variations vaudrait zéro alors
-- que le stock ne l'est pas, et l'invariant serait faux dès la première
-- vérification. Le stock actuel résulte de ventes et de livraisons antérieures
-- au journal : on le reprend en bloc, sans auteur, plutôt que d'attribuer à
-- quelqu'un des mouvements qu'il n'a pas saisis.
INSERT INTO public.mouvement_stock
    (produit_id, type, variation, stock_avant, stock_apres, commentaire, cree_le)
SELECT p.id,
       'INITIAL',
       p.quantite_stock,
       0,
       p.quantite_stock,
       'Reprise du stock existant à la mise en place du journal des mouvements',
       coalesce(p.cree_le, now())
FROM public.produit p;
